def _add_clause_if_absent(db, *, policy_version_id, coverage_id, clause_type, article_no, text, page_ref,
                           default_color, type_id=None, relevance=None):
    """text가 이미 해당 coverage_id에 존재하면 건너뛰고, 없으면 Clause(+선택적 ClauseIncidentMap)를 추가한다."""
    existing = (
        db.query(Clause)
        .filter(Clause.coverage_id == coverage_id, Clause.text == text)
        .first()
    )
    if existing:
        return existing, False

    clause = Clause(
        policy_version_id=policy_version_id,
        coverage_id=coverage_id,
        clause_type=clause_type,
        article_no=article_no,
        text=text,
        page_ref=page_ref,
        default_color=default_color,
    )
    db.add(clause)
    db.flush()

    if type_id is not None and clause_type != "서류":
        db.add(ClauseIncidentMap(
            clause_id=clause.clause_id, type_id=type_id,
            relevance=relevance, mapped_by="human", confidence=1.0,
        ))
    return clause, True


