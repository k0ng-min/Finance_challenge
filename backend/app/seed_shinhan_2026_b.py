def run():
    db = SessionLocal()
    try:
        product = db.query(Product).filter_by(product_code=PRODUCT_CODE).first()
        if not product:
            raise SystemExit("청크 a(app.seed_shinhan_2026_a)를 먼저 실행하세요.")
        pv = db.query(PolicyVersion).filter_by(
            product_id=product.product_id, version_label=VERSION_LABEL).first()

        coverages: dict[str, Coverage] = {}
        made = 0
        for title, (std_code, std_name, category, definition) in SPECIALS.items():
            std = get_or_create_coverage_std(db, std_code, std_name, category, False)
            cov = db.query(Coverage).filter_by(
                policy_version_id=pv.policy_version_id, raw_name=title).first()
            if not cov:
                cov = Coverage(
                    policy_version_id=pv.policy_version_id,
                    coverage_std_id=std.coverage_std_id,
                    raw_name=title, definition=definition,
                )
                db.add(cov); db.flush(); made += 1
            coverages[title] = cov

        added = 0
        for title, article_no, clause_type, page_ref, text in CLAUSES:
            exists = db.query(Clause).filter(
                Clause.policy_version_id == pv.policy_version_id,
                Clause.text == text,
            ).first()
            if exists:
                continue
            db.add(Clause(
                policy_version_id=pv.policy_version_id,
                coverage_id=coverages[title].coverage_id,
                clause_type=clause_type,
                article_no=article_no,
                text=text,
                page_ref=page_ref,
            ))
            added += 1
        db.commit()
        print(f"Coverage {made}개 생성 (전체 {len(SPECIALS)}개 중)")
        print(f"Clause {added}개 추가 (전체 {len(CLAUSES)}개 중)")
    finally:
        db.close()


if __name__ == "__main__":
    run()
