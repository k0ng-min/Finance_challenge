def run():
    """
    메리츠 2026년판 청크 2 시드 함수. 페이지 43-86의 22개 개별보장 특별약관을
    Coverage/Clause로 시드한다.

    멱등성: 같은 policy_version_id + clause.text 조합이 이미 있으면 건너뜀.
    Product/PolicyVersion은 청크 1(seed_meritz_2026_a.py)에서 이미 생성되었다고 가정하고
    조회만 한다.
    """
    db = SessionLocal()
    try:
        product = db.query(Product).filter_by(product_code=PRODUCT_CODE).first()
        if not product:
            raise RuntimeError(
                f"Product {PRODUCT_CODE} 를 찾을 수 없습니다. "
                "seed_meritz_2026_a.run()을 먼저 실행하세요."
            )
        policy_version = (
            db.query(PolicyVersion)
            .filter_by(product_id=product.product_id, version_label=VERSION_LABEL)
            .first()
        )
        if not policy_version:
            raise RuntimeError(
                f"PolicyVersion {VERSION_LABEL} 를 찾을 수 없습니다. "
                "seed_meritz_2026_a.run()을 먼저 실행하세요."
            )
        pv_id = policy_version.policy_version_id

        # 이 청크가 이미 시드됐으면(Coverage 생성이 idempotent하지 않으므로) 통째로 건너뛴다.
        if db.query(Coverage).filter_by(policy_version_id=pv_id, raw_name=COVERAGES[0]["raw_name"]).first():
            print("메리츠 2026년판 청크 2: 이미 시드됨, 건너뜀.")
            db.commit()
            return

        coverage_count = 0
        clause_count = 0

        for cov_def in COVERAGES:
            cov_std = get_or_create_coverage_std(
                db, cov_def["std_code"], cov_def["std_name"], cov_def["category"], cov_def["is_base"]
            )

            coverage = Coverage(
                policy_version_id=pv_id,
                coverage_std_id=cov_std.coverage_std_id,
                raw_name=cov_def["raw_name"],
                definition=None,
                limit_amount=None,
                deductible=None,
                waiting_condition=None,
            )
            db.add(coverage)
            db.flush()
            coverage_count += 1

            for clause_type, article_no, text, page_ref, color in cov_def["clauses"]:
                # coverage_id도 함께 걸어서 dedup한다. 서로 다른 특약(coverage)이 우연히 같은
                # 문구를 공유하는 경우(예: 상해입원일당 1일/4일 두 특약의 동일한 문구)가 있어
                # policy_version_id + text만으로 걸면 두 번째 특약의 조항이 사라진다.
                existing = (
                    db.query(Clause)
                    .filter_by(policy_version_id=pv_id, coverage_id=coverage.coverage_id, text=text)
                    .first()
                )
                if existing:
                    continue
                clause = Clause(
                    policy_version_id=pv_id,
                    coverage_id=coverage.coverage_id,
                    clause_type=clause_type,
                    article_no=article_no,
                    text=text,
                    page_ref=page_ref,
                    default_color=color,
                )
                db.add(clause)
                clause_count += 1

        db.commit()
        print("메리츠 2026년판 청크 2 시드 완료.")
        print(f"- Product: {PRODUCT_CODE}")
        print(f"- PolicyVersion: {VERSION_LABEL}")
        print(f"- Coverage: {coverage_count}개 (특별약관 22개)")
        print(f"- Clause: {clause_count}개")

    finally:
        db.close()


if __name__ == "__main__":
    run()
