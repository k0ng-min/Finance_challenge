def run():
    db = SessionLocal()
    try:
        if db.query(StandardClause).filter_by(standard_name=STANDARD_NAME).first():
            print(f"이미 시드됨 ({STANDARD_NAME}). 스킵합니다.")
            return

        for article in ARTICLES:
            db.add(StandardClause(
                standard_name=STANDARD_NAME,
                article_no=article["article_no"],
                title=article["title"],
                text=article["text"],
                amended_at=article["amended_at"],
                source_url=SOURCE_URL,
                downloaded_at=DOWNLOADED_AT,
                sha256=SHA256,
            ))
        db.commit()
        print(f"{STANDARD_NAME} 표준약관 {len(ARTICLES)}개 조문 시드 완료.")
    finally:
        db.close()


if __name__ == "__main__":
    run()
