def _get_or_none(db, model, **kwargs):
    """조회 헬퍼: 없으면 None 반환."""
    return db.query(model).filter_by(**kwargs).first()


def _coverage_exists(db, policy_version_id: int, std_code: str, raw_name: str) -> bool:
    """같은 Coverage가 이미 있는지 확인."""
    cov_std = db.query(CoverageStd).filter_by(std_code=std_code).first()
    if not cov_std:
        return False
    return db.query(Coverage).filter_by(
        policy_version_id=policy_version_id,
        coverage_std_id=cov_std.coverage_std_id,
        raw_name=raw_name
    ).first() is not None


def _clause_exists(db, policy_version_id: int, text: str) -> bool:
    """같은 policy_version과 text 조합이 이미 있는지 확인."""
    return db.query(Clause).filter_by(
        policy_version_id=policy_version_id,
        text=text
    ).first() is not None


def _add_clause(db, coverage_id: int | None, policy_version_id: int,
                clause_type: str, article_no: str, text: str, page_ref: str) -> Clause:
    """Clause 추가 (멱등성: 이미 있으면 건너뜀)."""
    if _clause_exists(db, policy_version_id, text):
        return None

    # clause_type -> default_color 매핑
