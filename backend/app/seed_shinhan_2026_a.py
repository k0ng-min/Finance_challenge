def run():
    db = SessionLocal()
    try:
        insurer, product, pv = seed_insurer_core(
            db,
            name=INSURER_NAME, code=INSURER_CODE,
            official_url="https://www.shinhanez.co.kr",
            product_name=PRODUCT_NAME, product_code=PRODUCT_CODE,
            channel="다이렉트", sale_start=None, collected_at=date(2026, 8, 24),
            version_label=VERSION_LABEL, effective_date=date(2026, 6, 6),
            source_url=SOURCE_URL, file_hash=FILE_HASH,
        )
        if insurer is None:
            # 이미 시드돼 있다 - 아래 조항 추가는 그대로 이어서 한다(idempotent).
            insurer = db.query(Insurer).filter_by(code=INSURER_CODE).first()
            product = db.query(Product).filter_by(product_code=PRODUCT_CODE).first()
            pv = db.query(PolicyVersion).filter_by(
                product_id=product.product_id, version_label=VERSION_LABEL).first()
            print(f"Insurer {INSURER_NAME} 이미 존재")
        else:
            print(f"Insurer {INSURER_NAME} / Product {PRODUCT_NAME} / PolicyVersion {VERSION_LABEL} 생성")

        std = get_or_create_coverage_std(db, "DEATH_INJURY", "상해사망·후유장해", "상해", True)
        coverage = db.query(Coverage).filter_by(
            policy_version_id=pv.policy_version_id, raw_name="상해사망·후유장해").first()
        if not coverage:
            coverage = Coverage(
                policy_version_id=pv.policy_version_id,
                coverage_std_id=std.coverage_std_id,
                raw_name="상해사망·후유장해",
                definition="보험기간 중 해외여행 도중 상해의 직접결과로 사망하거나 장해분류표에서 정한 장해상태가 된 경우",
            )
            db.add(coverage)
            db.flush()
            print("Coverage 상해사망·후유장해 생성")

        added = 0
        for article_no, clause_type, page_ref, text in COMMON_CLAUSES:
            exists = db.query(Clause).filter(
                Clause.policy_version_id == pv.policy_version_id,
                Clause.text == text,
            ).first()
            if exists:
                continue
            db.add(Clause(
                policy_version_id=pv.policy_version_id,
                coverage_id=None if clause_type == "공통" else coverage.coverage_id,
                clause_type=clause_type,
                article_no=article_no,
                text=text,
                page_ref=page_ref,
            ))
            added += 1
        db.commit()
        print(f"Clause {added}개 추가 (전체 {len(COMMON_CLAUSES)}개 중)")
    finally:
        db.close()


if __name__ == "__main__":
    run()
