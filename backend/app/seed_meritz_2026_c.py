def _add_clause(db, pv_id, coverage_id, clause_type, article_no, text, page_ref, color):
    existing = db.query(Clause).filter_by(policy_version_id=pv_id, text=text).first()
    if existing:
        return existing
    clause = Clause(
        policy_version_id=pv_id,
        coverage_id=coverage_id,
        clause_type=clause_type,
        article_no=article_no,
        text=text,
        page_ref=page_ref,
        default_color=color,
    )
    db.add(clause)
    db.flush()
    return clause


