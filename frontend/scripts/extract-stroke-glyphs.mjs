// "보험형광펜"을 진짜 필순(획 순서)대로 쓰는 애니메이션에 필요한 데이터를
// scripts/source/boheom-handwriting.html 에서 뽑아 src/generated/penStrokeGlyphs.ts
// 로 만든다.
//
// 원본 HTML은 글자마다
//   ① 획별 윤곽선(clipPath c{글자}_{획})
//   ② 그 획의 중심선(median, class="rev")과 그 획을 다 덮을 만한 붓 굵기
//   ③ 글자 전체의 완성된 글리프 윤곽선(class="glyph")
// 을 담고 있다. 중심선을 stroke-dasharray로 그어 나가면서 그걸 <mask>로 쓰고,
// 그 마스크를 해당 획의 윤곽선(clipPath)으로 잘라내면 "붓이 지나간 만큼만
// 그 획 모양대로" 글자가 드러난다 — 획 하나하나가 실제 필순대로 그어진다.
//
// 실행: node scripts/extract-stroke-glyphs.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "source/boheom-handwriting.html");
const OUT = resolve(here, "../src/generated/penStrokeGlyphs.ts");
const CHARS = [..."보험형광펜"];

const html = readFileSync(SRC, "utf8");

/** viewBox="-60 0 3895 880" */
const viewBox = /<svg[^>]*viewBox="([^"]+)"/.exec(html)[1].trim();

/** clipPath id -> 획 윤곽선 path */
const clips = new Map();
for (const m of html.matchAll(
  /<clipPath id="(c\d+_\d+)"[^>]*>\s*<path d="([^"]+)"\s*\/>\s*<\/clipPath>/g,
)) {
  clips.set(m[1], m[2]);
}

/** mask id -> [{ clipId, median, width }] (원본에 적힌 획 순서 그대로) */
const masks = new Map();
for (const m of html.matchAll(/<mask id="(m\d+)"[^>]*>([\s\S]*?)<\/mask>/g)) {
  const strokes = [];
  for (const s of m[2].matchAll(
    /<g clip-path="url\(#(c\d+_\d+)\)"><path class="rev" d="([^"]+)"[^>]*stroke-width="([\d.]+)"/g,
  )) {
    strokes.push({ clipId: s[1], median: s[2], width: Number(s[3]) });
  }
  masks.set(m[1], strokes);
}

/** 글자별 가로 위치 + 완성된 글리프 윤곽선 */
const placements = [];
for (const m of html.matchAll(
  /<g transform="translate\((-?[\d.]+),0\)"><g mask="url\(#(m\d+)\)"><g transform="([^"]+)"><path class="glyph" d="([^"]+)"\s*\/>/g,
)) {
  placements.push({ offsetX: Number(m[1]), maskId: m[2], glyphTransform: m[3], outline: m[4] });
}

if (placements.length !== CHARS.length) {
  throw new Error(`글자 수가 안 맞는다: ${placements.length} vs ${CHARS.length}`);
}

const glyphs = placements.map((p, i) => {
  const strokes = masks.get(p.maskId);
  if (!strokes?.length) throw new Error(`${p.maskId}에 획이 없다`);
  return {
    char: CHARS[i],
    offsetX: p.offsetX,
    glyphTransform: p.glyphTransform,
    outline: p.outline,
    strokes: strokes.map((s) => {
      const clip = clips.get(s.clipId);
      if (!clip) throw new Error(`${s.clipId} 윤곽선이 없다`);
      return { clip, median: s.median, width: s.width };
    }),
  };
});

// 실제 잉크가 차지하는 범위(viewBox 좌표) — 형광펜 띠를 글자 높이에 맞추는 데
// 쓰라고 같이 내보낸다. 획 윤곽선(clipPath)들의 좌표를 다 훑어서 구한다.
let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;
for (const g of glyphs) {
  for (const s of g.strokes) {
    const nums = s.clip.match(/-?[\d.]+/g).map(Number);
    for (let k = 0; k + 1 < nums.length; k += 2) {
      const x = nums[k] + g.offsetX;
      const y = nums[k + 1];
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
}
const inkBox = {
  x: Math.round(minX),
  y: Math.round(minY),
  width: Math.round(maxX - minX),
  height: Math.round(maxY - minY),
};

const banner = `// AUTO-GENERATED by scripts/extract-stroke-glyphs.mjs — 직접 수정하지 말 것
// 원본: scripts/source/boheom-handwriting.html (학교안심 민들레홀씨 R, KERIS, OFL
// 공공누리 1유형 · 출처표시 / 필순 데이터 포함)
//
// glyph 하나당: outline(완성된 글자 모양) + strokes(획 순서대로).
// strokes[i].median 을 stroke-dasharray로 그어 나가는 걸 <mask>로 쓰고,
// strokes[i].clip 으로 잘라내면 그 획만 필순대로 드러난다 — PenWriteCompass 참고.
`;

const body = `${banner}
export interface PenStroke {
  /** 이 획의 윤곽선 — 붓(median)이 이 모양 밖으로 삐져나가지 않게 잘라낸다. */
  clip: string;
  /** 이 획의 중심선 — 실제로 펜이 지나가는 궤적. */
  median: string;
  /** 이 획을 빠짐없이 덮는 붓 굵기(viewBox 좌표 단위). */
  width: number;
}

export interface PenStrokeGlyph {
  char: string;
  /** 글자 전체를 가로로 옮기는 양(viewBox 좌표 단위). */
  offsetX: number;
  /** 글리프 윤곽선을 화면 좌표로 뒤집는 transform. */
  glyphTransform: string;
  /** 다 쓴 글자의 완성된 모양. */
  outline: string;
  strokes: PenStroke[];
}

/** 모든 글자를 담는 하나의 좌표계. */
export const PEN_STROKE_VIEWBOX = ${JSON.stringify(viewBox)};

/** 실제 잉크가 차지하는 범위(viewBox 좌표) — 형광펜 띠 높이를 맞추는 데 쓴다. */
export const PEN_STROKE_INK_BOX = ${JSON.stringify(inkBox)};

export const PEN_STROKE_GLYPHS: PenStrokeGlyph[] = ${JSON.stringify(glyphs, null, 2)};
`;

writeFileSync(OUT, body, "utf8");

console.log(`viewBox: ${viewBox}`);
console.log(`ink box: ${JSON.stringify(inkBox)}`);
for (const g of glyphs) console.log(`  ${g.char}: ${g.strokes.length}획`);
console.log(`→ ${OUT}`);
