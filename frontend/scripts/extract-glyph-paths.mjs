// PenWriteCompass가 "보험형광펜"을 실제 폰트 모양 그대로 쓰는 것처럼 보이도록,
// 학교안심 민들레홀씨 R(한국교육학술정보원 KERIS, OFL) 폰트에서 각 글자의 실제
// SVG 윤곽선(outline path)을 추출해 src/generated/penGlyphPaths.ts로 저장한다.
// opentype.js는 이 스크립트에서만 쓰고 번들에는 포함하지 않는다 — 결과물인
// 생성 파일만 커밋한다.
//
// 다시 만들려면: scripts/fonts/Hakgyoansim-MindeulleholssiR.woff를 두고
// `node scripts/extract-glyph-paths.mjs` 실행.
import opentype from "opentype.js";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const fontPath = path.join(__dirname, "fonts", "Hakgyoansim-MindeulleholssiR.woff");
const outPath = path.join(__dirname, "..", "src", "generated", "penGlyphPaths.ts");

const CHARS = ["보", "험", "형", "광", "펜"];

const font = opentype.loadSync(fontPath);
const unitsPerEm = font.unitsPerEm;
// 글자마다 잉크 bbox로 viewBox를 따로 잡으면 글자마다 세로 위치(베이스라인)가
// 어긋난다 — 대신 폰트 전체의 ascender/descender를 공유 세로 범위로 써서 한
// 줄에 놓였을 때 베이스라인이 맞도록 한다.
const ascender = font.ascender;
const descender = font.descender;

const glyphs = CHARS.map((char) => {
  const glyph = font.charToGlyph(char);
  // getPath(x, y, fontSize)는 fontSize=unitsPerEm일 때 폰트 좌표를 그대로
  // SVG 좌표(y축 반전 포함)로 옮겨준다 — baseline이 y=0.
  const svgPath = glyph.getPath(0, 0, unitsPerEm);
  const d = svgPath.toPathData(2);
  return {
    char,
    d,
    x: 0,
    y: Number((-ascender).toFixed(2)),
    width: Number((glyph.advanceWidth ?? 0).toFixed(2)),
    height: Number((ascender - descender).toFixed(2)),
    advanceWidth: Number((glyph.advanceWidth ?? 0).toFixed(2)),
    // em 단위 렌더 폭 — <svg> 컨테이너 width를 이 값(em)으로 주면 실제
    // 폰트 자간과 동일한 가로 배치가 된다.
    advanceEm: Number(((glyph.advanceWidth ?? 0) / unitsPerEm).toFixed(4)),
  };
});

const banner = `// AUTO-GENERATED by scripts/extract-glyph-paths.mjs — 직접 수정하지 말 것.
// 학교안심 민들레홀씨 R(KERIS, OFL)에서 뽑은 "보험형광펜" 각 글자의 실제
// 윤곽선 path(d)와 SVG viewBox 정보. PenWriteCompass가 이 path를 그대로
// 채워서(fill) 보여주고, clip-path로 펜이 지나간 x좌표까지만 드러낸다.
`;

const body = `export interface PenGlyphPath {
  char: string;
  d: string;
  x: number;
  y: number;
  width: number;
  height: number;
  advanceWidth: number;
  advanceEm: number;
}

export const PEN_GLYPH_PATHS: PenGlyphPath[] = ${JSON.stringify(glyphs, null, 2)};
`;

writeFileSync(outPath, banner + "\n" + body, "utf-8");
console.log(`Wrote ${glyphs.length} glyph paths to ${outPath}`);
for (const g of glyphs) {
  console.log(`${g.char}: viewBox="${g.x} ${g.y} ${g.width} ${g.height}" advanceEm=${g.advanceEm}`);
}
